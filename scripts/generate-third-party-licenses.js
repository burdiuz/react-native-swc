#!/usr/bin/env node
// Regenerates THIRD_PARTY_LICENSES.md from the Rust crates that end up in libactualwave_swc.so.
//
// Needs `cargo` and a populated cargo registry (run a build first). Usage:
//   node scripts/generate-third-party-licenses.js [target-triple]   # default aarch64-linux-android
//
// Only normal (non-build, non-dev) dependencies reachable from this crate for the given target are
// listed — those are the crates compiled into the shared library. License texts are read from each
// crate's own LICENSE/COPYING/NOTICE files and de-duplicated by content.
const { execFileSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const TARGET = process.argv[2] || 'aarch64-linux-android';
const LICENSE_NAMES = ['LICENSE', 'LICENCE', 'COPYING', 'NOTICE', 'UNLICENSE'];

const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--filter-platform', TARGET], {
    cwd: path.join(ROOT, 'rust'),
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));

// Walk normal dependencies only (a dep_kinds entry whose kind is null).
const root = meta.resolve.root;
const seen = new Set();
const stack = [root];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of nodes.get(id).deps) {
    if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
  }
}
seen.delete(root);

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const crates = [...seen]
  .map((id) => pkgs.get(id))
  .sort((a, b) => cmp(a.name, b.name) || cmp(a.version, b.version));

function licenseFiles(pkg) {
  const dir = path.dirname(pkg.manifest_path);
  return fs
    .readdirSync(dir)
    .sort()
    .filter((name) => {
      const stem = name.toUpperCase().split('.')[0].split('-')[0];
      return LICENSE_NAMES.includes(stem) && fs.statSync(path.join(dir, name)).isFile();
    })
    .map((name) => [name, fs.readFileSync(path.join(dir, name), 'utf8').replace(/\r\n?/g, '\n').trim()]);
}

const byLicense = new Map();
const texts = new Map(); // sha -> text
const textUsers = new Map(); // sha -> ["name version"]
const missing = [];
for (const p of crates) {
  const lic = p.license || 'UNSPECIFIED';
  if (!byLicense.has(lic)) byLicense.set(lic, []);
  byLicense.get(lic).push(p);
  const files = licenseFiles(p);
  if (files.length === 0) missing.push(p);
  for (const [, txt] of files) {
    const sha = crypto.createHash('sha256').update(txt).digest('hex');
    texts.set(sha, txt);
    if (!textUsers.has(sha)) textUsers.set(sha, []);
    const label = `${p.name} ${p.version}`;
    if (!textUsers.get(sha).includes(label)) textUsers.get(sha).push(label);
  }
}

if (![...texts.values()].some((t) => t.includes('Apache License') && t.includes('Version 2.0'))) {
  console.error('error: no Apache-2.0 text found among dependencies; add one manually');
  process.exit(1);
}

const out = [];
const w = (line = '') => out.push(line);
w('# Third-party licenses\n');
w('`@actualwave/react-native-swc` itself is MIT-licensed (see `LICENSE`). The prebuilt native library');
w('`libactualwave_swc.so` shipped in this package statically links the Rust crates listed below,');
w('chiefly [SWC](https://swc.rs) (`swc_core`, Apache-2.0). Their licenses and notices follow.\n');
w(`_Generated by \`scripts/generate-third-party-licenses.js\` for target \`${TARGET}\` — ${crates.length} crates._\n`);
w('## Summary by license\n');
w('| License | Crates |\n| --- | ---: |');
[...byLicense.entries()]
  .sort((a, b) => b[1].length - a[1].length || cmp(a[0], b[0]))
  .forEach(([lic, items]) => w(`| ${lic} | ${items.length} |`));
w('\n## Crates\n');
w('| Crate | Version | License | Source |\n| --- | --- | --- | --- |');
for (const p of crates) {
  const repo = p.repository || p.homepage || `https://crates.io/crates/${p.name}`;
  w(`| ${p.name} | ${p.version} | ${p.license || 'UNSPECIFIED'} | ${repo} |`);
}
if (missing.length) {
  w('\n## Crates published without a license file\n');
  w('These crates ship no license file in their crates.io package; the license below is the one they');
  w('declare in `Cargo.toml`. Their license text is the standard text of the named license (the');
  w('Apache-2.0 text is reproduced in the next section).\n');
  w('| Crate | License | Authors |\n| --- | --- | --- |');
  for (const p of missing) {
    const authors = (p.authors || []).join(', ') || 'see repository';
    w(`| ${p.name} ${p.version} | ${p.license || 'UNSPECIFIED'} | ${authors.replaceAll('|', '/')} |`);
  }
}
w('\n## License texts\n');
[...texts.entries()]
  .sort((a, b) => cmp(textUsers.get(a[0])[0], textUsers.get(b[0])[0]))
  .forEach(([sha, txt], i) => {
    let users = textUsers.get(sha);
    if (users.length > 6) users = [...users.slice(0, 6), `and ${users.length - 6} more`];
    w(`### ${i + 1}. Used by: ${users.join(', ')}\n`);
    w('```text\n' + txt + '\n```\n');
  });

fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_LICENSES.md'), out.join('\n'));
console.log(`${crates.length} crates, ${texts.size} distinct license texts, ${missing.length} without a license file`);
for (const [lic, items] of [...byLicense.entries()].sort((a, b) => cmp(a[0], b[0]))) {
  console.log(`  ${lic}: ${items.length}`);
}
